"""Generate End of Destiny static objects from eod4sdl's statinfo[] (wl_act1.cpp).

Writes:
  Scripts/AReyeP/EoDStatics.zs  one class per EoD static: decorations (solid
                                 or walk-over, flat wall sprites, full-bright),
                                 and pickups subclassing the TC/SR item with
                                 EoD's art
  stdout                         the TileCodes plane-1 lines for those codes

statinfo index -> map code: 0-66 are codes 23-89, 69-153 are codes 270-354
(eod4sdl ScanInfoPlane: SpawnStatic(tile - 23) / SpawnStatic(tile - 201)).

usage: geneodactors.py WL_ACT1_CPP > plane1.txt
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import eod_sprites

ROOT = Path(__file__).resolve().parent.parent

# Pickup type -> base class (TC or SR); EoD subclasses only swap the sprite
PICKUPS = {
    "bo_alpo": "SRSmallMedkit", "bo_firstaid": "FirstAidKit", "bo_food": "PlateofFood",
    "bo_key1": "YellowKey", "bo_key2": "BlueKey", "bo_key3": "SRBloodKey", "bo_key4": "SRElevatorKey",
    "bo_cross": "JeweledCross", "bo_chalice": "Chalice", "bo_bible": "Chest", "bo_crown": "Crown",
    "bo_diamond": "SRBlackDiamond", "bo_clip": "WolfClip", "bo_clip2": "WolfClip", "bo_25clip": "WolfClipBox",
    "bo_sclip": "SRAmmo2", "bo_s25clip": "SRAmmo2Crate", "bo_machinegun": "WolfMachineGun",
    "bo_mk3": "SRMk3", "bo_mk4": "SRMk4", "bo_spear": "SpearofDestiny", "bo_gibs": "BoneswithBlood",
    "bo_fullheal": "SRArtefactLife", "bo_landmine": "SRLandmine", "bo_goodberry": "SRGoodBerryBush",
    "bo_badberry": "SRBadBerryBush", "bo_poison": "SRToxicSlime", "bo_pistol": "SRPistolPickup",
    "bo_god": "SRGodModeArtefact", "bo_death": "SRDeathArtefact", "bo_backpack": "EoDBackpack",
    "bo_rifle": "EoDRifle", "bo_rifleclip": "EoDRifleAmmo", "bo_launcher": "EoDRocketLauncher",
    "bo_rocketbox": "EoDRocketBox", "bo_save": "EoDSaveArtefact", "bo_fury": "EoDFury",
    "bo_portmed": "EoDPortableMedkit",
}
# Statics eod4sdl animates through four frames (wl_draw.cpp DrawScaleds), tics
# per frame halved from 70 Hz: torches and flames every 12, artefacts every 10
ANIMATED = {
    "SPR_STAT_OTORCH1": 6, "SPR_STAT_ITORCH1": 6, "SPR_STAT_FLAME1": 6,
    "SPR_STAT_GOD1": 5, "SPR_STAT_TELE1": 5, "SPR_STAT_FURY1": 5, "SPR_STAT_DEATH1": 5,
    "SPR_STAT_SAVEGAME1": 5, "SPR_STAT_NEWLIFE1": 5, "SPR_STAT_REGEN1": 5,
}

# Pickups whose art is drawn as a floor hazard (SRFloorHazard) rather than an Inventory
HAZARDS = {"SRLandmine", "SRToxicSlime", "SRDeathArtefact"}


def parse_statinfo(path):
    src = open(path, encoding="latin1").read()
    block = src[src.index("statinfo[] ="):]
    block = block[block.index("{") + 1:block.index("};")]
    entries = []
    for line in block.split("\n"):
        m = re.match(r"\s*\{([^}]*)\},?\s*(?://\s*(.*))?", line)
        if not m:
            continue
        parts = [p.strip() for p in m.group(1).split(",")]
        if parts[0] == "-1":
            break
        entries.append((parts[0], parts[1] if len(parts) > 1 else "none",
                        parts[2] if len(parts) > 2 else "", (m.group(2) or "").strip()))
    return entries


def sprite_state(spr):
    """(sprite, frame, stock) for an EoD statinfo sprite. Stock Spear positions are drawn
    into the TC's names (e.g. LIFEA0), EoD-only ones into tools/eod_sprites.py names."""
    if spr not in eod_sprites.ENUM:
        return None, None, False
    i = eod_sprites.ENUM.index(spr)
    for a, b in eod_sprites.POSITIONAL:
        if a <= i <= b:
            # Every EoD page also has a generic name (E###<frame>0), which works even
            # where Spear's slot has no usable sprite name (e.g. DEATHCAM, EoD's barrel)
            return "E%03d" % (i // 26), chr(0x41 + i % 26), True
    sprite, frame = eod_sprites.frame(spr)
    return sprite, frame, False


def spawn_line(spr, sprite, frame, bright):
    """The Spawn state: one frame held, or four looping for animated statics."""
    b = " Bright" if bright else ""
    if spr in ANIMATED:
        frames = "".join(chr(ord(frame) + k) for k in range(4))
        return ["\t\t\t%s %s %d%s;" % (sprite, frames, ANIMATED[spr], b), "\t\t\tLoop;"]
    return ["\t\t\t%s %s -1%s;" % (sprite, frame, b), "\t\t\tStop;"]


def class_name(comment, idx):
    words = re.sub(r"[^A-Za-z0-9 ]", " ", comment).title().split()
    name = "".join(words)[:28] or "Static%d" % idx
    return "EoDObj" + name


def main():
    entries = parse_statinfo(sys.argv[1])
    zs = ["// Generated by tools/geneodactors.py from eod4sdl's statinfo[]; do not edit by hand.",
          "// End of Destiny statics. Art is VSWAP.EOD via Data/GraphicMaps/EOD.txt (tools/eod_sprites.py).", ""]
    plane1 = []
    used = set()

    for idx, (spr, kind, flags, comment) in enumerate(entries):
        if idx <= 66:
            code = 23 + idx
        elif 69 <= idx <= 153:
            code = 201 + idx
        else:
            continue  # teleporters (67, 68) and triggers (154+) are separate systems

        sprite, frame, stock = sprite_state(spr)
        name = class_name(comment, idx)
        while name in used:
            name += "2"
        used.add(name)
        bright = "FL_FULLBRIGHT" in flags
        flat = "FL_DIR_HORIZ_MID" in flags or "FL_DIR_VERT_MID" in flags

        if kind.startswith("bo_"):
            base = PICKUPS.get(kind)
            if not base:
                continue
            if stock:
                # stock-position art: the TC/SR base class already shows it
                plane1.append('\t\t%d = "%s"; // %s' % (code, base, comment))
                continue
            zs += ["class %s : %s // %s" % (name, base, comment), "{", "\tStates", "\t{", "\t\tSpawn:"] + \
                spawn_line(spr, sprite, frame, bright) + ["\t}", "}", ""]
        else:
            if sprite is None or spr == "SPR_DEMO":
                continue  # placeholders (warp entry / tele artefact are separate systems)
            base = ("WolfWallSprite" if kind == "block" else "SRFlatDecoration") if flat else ("SRSolidDecoration" if kind == "block" else "SRDecoration")
            body = ["class %s : %s // %s" % (name, base, comment), "{"]
            if bright:
                body += ["\tDefault", "\t{", "\t\t+BRIGHT", "\t}", ""]
            body += ["\tStates", "\t{", "\t\tSpawn:"] + spawn_line(spr, sprite, frame, bright) + ["\t}"]
            if flat:
                body += ["", "\toverride void PostBeginPlay()", "\t{", "\t\tSuper.PostBeginPlay();",
                         "\t\tangle = %d; // %s" % (90 if "HORIZ" in flags else 0, "lies east-west" if "HORIZ" in flags else "lies north-south"),
                         "\t}"]
            zs += body + ["}", ""]
        plane1.append('\t\t%d = "%s"; // %s' % (code, name, comment))

    (ROOT / "Scripts/AReyeP/EoDStatics.zs").write_text("\n".join(zs))
    print("\n".join(plane1))


if __name__ == "__main__":
    main()
