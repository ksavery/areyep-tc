"""Generate the per-game VSWAP definition files from the staged data.

Writes (all committed; they hold names and sizes only, no game data):
  Data/GraphicMaps/<FAMILY>.txt   VSWAP page -> canvas name tables (WFD.txt: the
                                  TC's Wolfenstein 3D tables, for Wolfendoom)
  AnimDefs.AReyeP.txt             canvastexture declarations for new names
  Textures.AReyeP.txt             placeholder Sprite entries so the engine
                                  registers those names as sprites

usage: gendefs.py STAGED-DIR
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import graphicmap
import eod_sprites
import sr_sprites
import wolfdata
from tcpath import TC

ROOT = Path(__file__).resolve().parent.parent

# family -> (VSWAP file, wall prefix, generic sprite prefix, sprite layout module or None);
# map extensions -> family live in Scripts/AReyeP/Games.zs
FAMILIES = {
    "SR": ("VSWAP.SR", "SR/Wall", "S", sr_sprites),
    "EOD": ("VSWAP.EOD", "EoD/Wall", "E", eod_sprites),
}

HEADER = "// Generated by tools/gendefs.py from the staged VSWAP; do not edit by hand.\n"
SPRITE_CANVAS = 'canvastexture "%s" 64 64 translucent offset 32 64\n'
# Frames held like player weapons (NoShadowMask in EXTRA_FLAGS) sit on screen as
# the TC's own weapon canvases do (CCGUA0 and friends in AnimDefs.txt)
WEAPON_CANVAS = 'canvastexture "%s" 64 64 translucent offset -128 -97\n'


def generic_name(prefix, index):
    return "%s%03i%c0" % (prefix, index // 26, 0x41 + index % 26)


def sprite_table(layout, count):
    """Return (per-index [(name, flags)], names that need new canvases)."""
    table = [[] for _ in range(count)]
    new = []
    spear = graphicmap.read_list(TC / "Data/GraphicMaps/SD1.txt")
    for first, last in layout.POSITIONAL:
        for i in range(first, last + 1):
            table[i] += [(n, f) for n, f in spear[i] if n]
    for first, last, old, prefix in layout.RENAMED:
        renamed = {i: [(n.replace(old, prefix), f) for n, f in spear[i]] for i in range(first, last + 1)}
        # Frames drawn from only one angle (e.g. attack frame E1) are fine for the
        # stock actors because the TC ships the other rotations as PNGs; renamed
        # sprites have no such images, so make those frames rotation 0 (all angles).
        rotations = {}
        for names in renamed.values():
            for n, _ in names:
                rotations.setdefault(n[:5], set()).add(n[5])
        for i, names in renamed.items():
            for n, f in names:
                if rotations[n[:5]] == {"1"}:
                    n = n[:5] + "0"
                table[i].append((n, f))
                new.append(n)
    for prefix, pages in layout.EXTRA.items():
        for frame, i in enumerate(pages):
            name = "%s%c0" % (prefix, 0x41 + frame)
            table[i].append((name, list(getattr(layout, "EXTRA_FLAGS", {}).get(prefix, []))))
            new.append(name)
        # Aliases reuse names another family already declares: no new canvases
        alias = getattr(layout, "ALIASES", {}).get(prefix)
        for frame, i in enumerate(pages if alias else []):
            table[i].append(("%s%c0" % (alias, 0x41 + frame), list(getattr(layout, "EXTRA_FLAGS", {}).get(prefix, []))))
        rotated = getattr(layout, "ROTATED", {}).get(prefix)
        for view, i in enumerate(pages[:8] if rotated else []):
            name = "%sA%d" % (rotated, view + 1)
            table[i].append((name, []))
            new.append(name)
    return table, new


def format_entry(index, names):
    if not names:
        return ['\t\t"";']
    if len(names) == 1 and not names[0][1]:
        return ['\t\t"%s";' % names[0][0]]
    out = ["", "\t\t%i" % index, "\t\t{"]
    for n, flags in names:
        out.append('\t\t\t"%s"%s' % (n, " { %s; }" % "; ".join(flags) if flags else ";"))
    out += ["\t\t}", ""]
    return out


def main():
    staged = Path(sys.argv[1])
    anim = [HEADER]
    sprites_tx = [HEADER]
    for family, (vswap, wallprefix, sprprefix, layout) in FAMILIES.items():
        vs = wolfdata.VSwap((staged / vswap).read_bytes())
        sprites = vs.sound_start - vs.sprite_start
        lines = [HEADER, family, "{",
                 '\tPalette = "%s";' % ("EoD.pal" if family == "EOD" else "Spear.pal"),  # EoD.pal: from SPEAR.EXE, in the data pack
                 '\tSpritePrefix = "%s";' % sprprefix,
                 "\tNoShadowMask = true;",
                 "", "\tTextures", "\t{"]
        lines += ['\t\t"%s%04i";' % (wallprefix, i) for i in range(vs.sprite_start)]
        lines += ["\t}"]

        new = []
        if layout:
            table, new = sprite_table(layout, sprites)
            # Trailing unnamed pages need no entries; they still get generic names
            while table and not table[-1]:
                table.pop()
            lines += ["", "\tSprites", "\t{"]
            for i, names in enumerate(table):
                lines += format_entry(i, names)
            lines += ["\t}"]
        lines += ["}", ""]
        (ROOT / "Data/GraphicMaps" / f"{family}.txt").write_text("\n".join(lines))

        anim.append(f"\n// {family}: {vs.sprite_start} walls, {sprites} sprites\n")
        anim += ['canvastexture "%s%04i" 64 64\n' % (wallprefix, i) for i in range(vs.sprite_start)]
        names = [generic_name(sprprefix, i) for i in range(sprites)] + new
        held = [p for p, f in getattr(layout, "EXTRA_FLAGS", {}).items() if "NoShadowMask" in f]
        anim += [(WEAPON_CANVAS if any(n.startswith(p) for p in held) else SPRITE_CANVAS) % n for n in names]
        sprites_tx.append(f"\n// {family}\n")
        sprites_tx += ["Sprite %s, 64, 64 { }\n" % n for n in names]
        print(f"{family}: {vs.sprite_start} walls, {sprites} sprites, {len(new)} named sprite frames")
    (ROOT / "AnimDefs.AReyeP.txt").write_text("".join(anim))
    (ROOT / "Textures.AReyeP.txt").write_text("".join(sprites_tx))
    write_wd()


def write_wd():
    """Wolfendoom keeps Wolfenstein 3D's VSWAP layout, so it uses the TC's own
    Wolf3D tables (Default.txt) under its own name. A data set without a table
    of its own would get whichever game's tables the last-picked rules name."""
    default = (TC / "Data/GraphicMaps/Default.txt").read_text()
    name = "Default // Wolf3D"
    if default.count(name) != 1:
        sys.exit(f"{TC}/Data/GraphicMaps/Default.txt: no '{name}' block to copy")
    header = "// Generated by tools/gendefs.py from the TC's Data/GraphicMaps/Default.txt; do not edit by hand.\n"
    (ROOT / "Data/GraphicMaps/WFD.txt").write_text(header + default.replace(name, "WFD // Wolfendoom: Wolfenstein 3D's layout"))
    print("WD: the TC's Wolfenstein 3D tables")


if __name__ == "__main__":
    main()
