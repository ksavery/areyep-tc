"""Generate tools/eod_sprites.py from eod4sdl's sprite enum (wl_def.h).

EoD's VSWAP follows Kyle Albert's EOD4SDL enum exactly for the 662 sprites the
original has (his build appends SPR_STAT_XMASPINE). Stock Spear ranges map to
the TC's names; every other enum group gets a 4-character EoD sprite name with
frames A, B, C... in enum order.

usage: geneodsprites.py WL_DEF_H > tools/eod_sprites.py
"""
import re
import sys

SPEAR_RANGES = [(0, 102), (142, 306), (326, 376), (385, 420)]  # same slots as Spear/SR
CLONE = (103, 141)  # Spear's dog slot holds the suicide clone


def enum_names(path):
    src = open(path, encoding="latin1").read()
    body = src[src.index("SPR_DEMO"):]
    body = body[:body.index("}")]
    out, stack = [], []
    for line in body.split("\n"):
        t = line.strip()
        m = re.match(r"#(ifdef|ifndef|if|else|elif|endif)\s*(.*)", t)
        if m:
            kind, arg = m.groups()
            arg = arg.split("//")[0].strip()
            if kind == "ifdef":
                stack.append(arg == "SPEAR")
            elif kind == "ifndef":
                stack.append(arg != "SPEAR")      # APOGEE_* are not defined
            elif kind == "if":
                stack.append(False)
            elif kind == "elif":
                stack[-1] = False
            elif kind == "else":
                stack[-1] = not stack[-1]
            elif kind == "endif":
                stack.pop()
            continue
        if not all(stack):
            continue
        t = re.sub(r"//.*", "", t)
        out += re.findall(r"\b([A-Z][A-Z0-9_]+)\b(?:\s*=\s*\d+)?\s*,?", t)
    return out


def group(name):
    """SPR_STAT_OTORCH3 -> STAT_OTORCH, SPR_TURRET_S5 -> TURRET, SPR_HEINRICH_DIE2 -> HEINRICH."""
    n = name[4:] if name.startswith("SPR_") else name
    n = n.replace("STAT_STAT_", "STAT_")  # eod4sdl typo: SPR_STAT_STAT_SAVEGAME2
    n = re.sub(r"_(S|W\d|W|SHOOT|DIE|DEAD|AIM|PAIN|JUMP|FIRE|ATK|TIRED|EXP|TRAIL)\d*(_\d+)?$", "", n)
    n = re.sub(r"(READY|ATK\d)$", "", n)
    n = re.sub(r"\d+$", "", n)
    return n


def main():
    names = enum_names(sys.argv[1])
    count = 662  # sprites in the original EoD VSWAP
    taken = set(range(CLONE[0], CLONE[1] + 1))
    for a, b in SPEAR_RANGES:
        taken |= set(range(a, b + 1))

    extra, order = {}, []
    for i in range(count):
        if i in taken:
            continue
        g = group(names[i])
        if g not in extra:
            extra[g] = []
            order.append(g)
        extra[g].append(i)

    print('"""End of Destiny VSWAP sprite layout -> sprite names (generated by')
    print('tools/geneodsprites.py from eod4sdl\'s wl_def.h; enum index = VSWAP index)."""')
    print()
    print("POSITIONAL = %r" % SPEAR_RANGES)
    print('RENAMED = [(%d, %d, "WDOG", "SCLN")]' % CLONE)
    print()
    print("# enum group -> (sprite name, VSWAP indices for frames A, B, C...)")
    print("EXTRA = {")
    used = set()
    for n, g in enumerate(order):
        sprite = "D%03d" % n
        used.add(sprite)
        print('    "%s": %r,  # %s' % (sprite, extra[g], g))
    print("}")
    print()
    print("# Frames held like player weapons must not get the shadow mask")
    weapons = [("D%03d" % n) for n, g in enumerate(order) if g in ("MK", "RIFLE", "LAUNCHER", "SPEAR")]
    print("EXTRA_FLAGS = {%s}" % ", ".join('"%s": ["NoShadowMask"]' % w for w in weapons))
    print()
    print("# Groups whose first eight pages are the eight views of one frame: also drawn")
    print("# as R### frame A rotations 1-8 (D### keeps every page as its own frame)")
    rot = [("D%03d" % n) for n, g in enumerate(order) if g in ("TURRET", "FIREBALL_", "HROCKET_", "SPEARPROJ_")]
    print("ROTATED = {%s}" % ", ".join('"%s": "R%s"' % (d, d[1:]) for d in rot))
    print()
    print("# Groups also drawn into SR's names, so the SR classes EoD shares show EoD art")
    alias = {"MK": "SRMK", "STAT_MK": "SRM4"}
    print("ALIASES = {%s}" % ", ".join('"D%03d": "%s"' % (n, alias[g]) for n, g in enumerate(order) if g in alias))
    print()
    print("GROUPS = {%s}" % ", ".join('"%s": "D%03d"' % (g, n) for n, g in enumerate(order)))
    print()
    print("# eod4sdl sprite enum names by VSWAP index")
    print("ENUM = %r" % names[:count])
    print("""

def frame(enum_name):
    \"\"\"(sprite, frame letter) an EoD enum sprite was drawn into, e.g. ("D017", "A").\"\"\"
    i = ENUM.index(enum_name)
    for sprite, pages in EXTRA.items():
        if i in pages:
            return sprite, chr(0x41 + pages.index(i))
    raise KeyError(enum_name + " is not an EoD-only sprite")""")


if __name__ == "__main__":
    main()
