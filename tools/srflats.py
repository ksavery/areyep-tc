"""Generate Scripts/AReyeP/SRFlats.zs: for each of SR's wall codes, the End of
Destiny floor and ceiling closest in colour to that wall, so a room walled in
wood gets a wooden floor, one in blue stone a blue one, and so on.

usage: python3 tools/srflats.py run   (reads run/VSWAP.SR and run/VSWAP.EOD)
"""
import sys
from pathlib import Path

from PIL import ImageStat

sys.path.insert(0, str(Path(__file__).parent))
import wolfdata
from sheet import load_palette, render_wall
from tcpath import TC

ROOT = Path(__file__).resolve().parent.parent

# The pages End of Destiny's own maps use for floors and for ceilings (its
# row 0), less the snow, lava and the brick one only its first level has
# (no earth: SR's indoors are never dirt, and the outside gets its own)
FLOORS = [192, 195, 196, 198, 199, 200, 203, 204, 205, 206, 207, 211, 212, 213, 216]
CEILINGS = [200, 201, 202, 207, 208, 209, 210, 214, 215, 217, 218, 219, 220, 221, 222]
WALLCODES = range(1, 90)  # Spear's wall codes; 90 and up are doors

# Where colour alone picks wrong: rock walls get a rock floor and ceiling, and
# wooden ones (slats, planks, panelling) wooden floors and ceilings
ROCK, ROCKY = 216, {8, 29, 30, 31, 61, 64, 65, 86}
WOODFLOOR, WOODCEILING, WOODEN = 195, 217, {7, 50, 53, 83, 84}
# and the white catacomb walls (white brick and stone, skull niches, cells) cobbles
COBBLES, CATACOMB = 215, {17, 23, 73, 74, 75, 76, 77, 78}


def average(img):
    return ImageStat.Stat(img.convert("RGB")).mean


def material(img):
    """A wall's colour from its outer 8 pixels: the stone, wood or brick behind
    any banner, portrait or emblem in the middle"""
    img = img.convert("RGB")
    px = [img.getpixel((x, y)) for y in range(64) for x in range(64) if x < 8 or x >= 56 or y < 8 or y >= 56]
    return [sum(p[i] for p in px) / len(px) for i in range(3)]


def nearest(colour, pages, means):
    return min(pages, key=lambda p: sum((a - b) ** 2 for a, b in zip(colour, means[p])))


def main():
    run = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "run")
    sr = wolfdata.VSwap(wolfdata.read(str(run / "VSWAP.SR")))
    eod = wolfdata.VSwap(wolfdata.read(str(run / "VSWAP.EOD")))
    spear = load_palette(str(TC / "Data/Palettes/Spear.pal"))
    eodpal_path = ROOT / "run" / "eod.pal"
    import zipfile
    with zipfile.ZipFile(run / "AReyeP-data.pk3") as z:
        eodpal_path.write_bytes(z.read("Data/Palettes/EoD.pal"))
    eodpal = load_palette(str(eodpal_path))
    eodpal_path.unlink()

    means = {p: average(render_wall(eod, p, eodpal)) for p in set(FLOORS + CEILINGS)}
    floors, ceilings = [], []
    for code in WALLCODES:
        page = (code - 1) * 2
        if page >= sr.sprite_start:
            floors.append(0)
            ceilings.append(0)
            continue
        colour = material(render_wall(sr, page, spear))
        if code in ROCKY:
            floors.append(ROCK)
            ceilings.append(ROCK)
        elif code in WOODEN:
            floors.append(WOODFLOOR)
            ceilings.append(WOODCEILING)
        elif code in CATACOMB:
            floors.append(COBBLES)
            ceilings.append(nearest(colour, CEILINGS, means))
        else:
            floors.append(nearest([c * 0.8 for c in colour], FLOORS, means))  # floors read darker
            ceilings.append(nearest(colour, CEILINGS, means))

    out = ["// Generated by tools/srflats.py from SR's and End of Destiny's VSWAPs; do not edit by hand.",
           "// SR wall code (1-89) -> the End of Destiny floor and ceiling page closest to it in colour.",
           "class SRFlatTable",
           "{",
           "\tstatic const int floors[] = { 0, " + ", ".join(map(str, floors)) + " };",
           "\tstatic const int ceilings[] = { 0, " + ", ".join(map(str, ceilings)) + " };",
           "}",
           ""]
    (ROOT / "Scripts/AReyeP/SRFlats.zs").write_text("\n".join(out))
    print("Scripts/AReyeP/SRFlats.zs: %d wall codes" % len(floors))


if __name__ == "__main__":
    main()
